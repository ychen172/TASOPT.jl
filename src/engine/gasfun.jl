"""
    gasfun(igas, t)

Computes properties of a thermally-perfect gas
with some variable specific heat cp[T].

!!! details "🔃 Inputs and Outputs"
    **Input:**
    - `igas`: index specifying the gas (see if blocks below for list)
    - `t`: temperature T in Kelvin

    **Output:**
    - `s`: entropy-complement function s[T]
    - `s_t`: ds/dT
    - `h`: complete enthalpy function h[T]
    - `h_t`: dh/dT
    - `cp`: specific heat cp[T]
    - `r`: ideal-gas constant R


The adiabatic pressure change over a process 1->2 with some polytropic efficiency epol is:

``\\ p2  = \\ p1  exp [   epol   (s2-s1)/R ] ``   compression

``\\ p2  = \\ p1  exp [ (1/epol) (s2-s1)/R ] ``   expansion
"""
function gasfun(igas, t)

    if (igas == 1)
        s, h, cp, r = gas_N2(t)
    elseif (igas == 2)
        s, h, cp, r = gas_O2(t)
    elseif (igas == 3)
        s, h, cp, r = gas_CO2(t)
    elseif (igas == 4)
        s, h, cp, r = gas_H2O(t)
    elseif (igas == 5)
        s, h, cp, r = gas_Ar(t)
    elseif (igas == 11)
        s, h, cp, r = gas_CH4(t)
    elseif (igas == 12)
        s, h, cp, r = gas_C2H6(t)
    elseif (igas == 13)
        s, h, cp, r = gas_C3H8(t)
    elseif (igas == 14)
        s, h, cp, r = gas_C4H10(t)
    elseif (igas == 18)
        s, h, cp, r = gas_C8H18(t)
    elseif (igas == 24)
        s, h, cp, r = gas_C14H30(t)
    elseif (igas == 25)
        s, h, cp, r = gas_JetFuel(t)
    elseif (igas == 32)
        s, h, cp, r = gas_C2H5OH(t)
    elseif (igas == 322431)#Fuel 32 blend with fuel 24 with 31% blend of the first fuel
        s, h, cp, r = gas_C2H5OHJetA31Blend(t)
    elseif (igas == 322429)#Fuel 32 blend with fuel 24 with 29% blend of the first fuel
        s, h, cp, r = gas_C2H5OHJetA29Blend(t)    
    elseif (igas == 322471)#Fuel 32 blend with fuel 24 with 71% blend of the first fuel
        s, h, cp, r = gas_C2H5OHJetA71Blend(t)    
    elseif (igas == 40)
        s, h, cp, r = gas_H2(t)
    else
        error("GASFUN: undefined gas index: ", igas, " & code=0")
    end
    s_t = cp / t
    h_t = cp
    return s, s_t, h, h_t, cp, r
end # gasfun

"""
    gaschem(igas)

Returns number of C,H,O,N atoms in gas molecule, for the gases implemented in function gasfun above.

!!! details "🔃 Inputs and Outputs"
    **Input:**
    - `igas`: index specifying the gas (see if blocks below for list)

    **Output:**
    - `nchon(.)`: number of C,H,O,N atoms in gas molecule

"""
function gaschem(igas)

    kc = 1
    kh = 2
    ko = 3
    kn = 4

    nchon = [0, 0, 0, 0]
    buf = Zygote.Buffer(nchon, length(nchon))
    for i = 1:length(nchon)
        buf[i] = nchon[i]
    end

    if (igas == 1)  #   N2
        buf[kn] = 2
    elseif (igas == 2)  #   O2
        buf[ko] = 2
    elseif (igas == 3)  #   CO2
        buf[kc] = 1
        buf[ko] = 2
    elseif (igas == 4)  #   H2O
        buf[kh] = 2
        buf[ko] = 1
    elseif (igas == 5)  #   Ar

    elseif (igas == 11)  #   CH4
        buf[kc] = 1
        buf[kh] = 4
    elseif (igas == 12)  #   C2H6
        buf[kc] = 2
        buf[kh] = 6
    elseif (igas == 13)  #   C3H8
        buf[kc] = 3
        buf[kh] = 8
    elseif (igas == 14)  #   C4H10
        buf[kc] = 4
        buf[kh] = 10
    elseif (igas == 18)  #   C8H18
        buf[kc] = 8
        buf[kh] = 18
    elseif (igas == 24)  #   C14H30
        buf[kc] = 14
        buf[kh] = 30
    elseif (igas == 25)  #   Jet Fuel
        buf[kc] = 16
        buf[kh] = 31
    elseif (igas == 32)  #   C2H5OH
        buf[kc] = 2
        buf[kh] = 6
        buf[ko] = 1
        buf[kn] = 0
    elseif (igas == 322431)   #   Fuel 32 blend with fuel 24 with 31% blend of the first fuel
        buf[kc] = 6  #6.5543
        buf[kh] = 14 #14.8424
        buf[ko] = 1  #1
        buf[kn] = 0  #0
    elseif (igas == 322429)   #   Fuel 32 blend with fuel 24 with 29% blend of the first fuel
        buf[kc] = 7  #6.5543
        buf[kh] = 16 #14.8424
        buf[ko] = 1  #1
        buf[kn] = 0  #0
    elseif (igas == 322471)   #   Fuel 32 blend with fuel 24 with 71% blend of the first fuel
        buf[kc] = 6  
        buf[kh] = 15 
        buf[ko] = 2  
        buf[kn] = 0  
    elseif (igas == 40)  #   H2
        buf[kc] = 0
        buf[kh] = 2
    else
        error("GASFUN: undefined gas index: ", igas, " & code=0")
    end
    nchon = copy(buf)
    return nchon
end # gaschem

